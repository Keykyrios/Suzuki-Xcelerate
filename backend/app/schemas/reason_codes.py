class Reason(StrictModel):
    """One structured explanation element."""

    code: ReasonCode
    subject: str | None = None
    detail: str | None = None
    value: float | None = None
    unit: str | None = None

    def render(self) -> str:
        text = self.code.value
        if self.subject:
            text = f"{text}:{self.subject}"
        return text
